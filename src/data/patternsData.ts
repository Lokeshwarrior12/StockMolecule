export type PatternFamily =
  | 'Single-Candle'
  | 'Dual-Candle'
  | 'Triple & Multi-Candle'
  | 'Classical Chart & Breakout';

export type PatternBias = 'Bullish' | 'Bearish' | 'Neutral';

export interface CandleRenderBar {
  /** Body bottom Y in 0..100 SVG space (where higher number = lower price) */
  openY: number;
  closeY: number;
  highY: number;
  lowY: number;
  bull: boolean;
  /** Optional neutral doji color */
  doji?: boolean;
}

export interface PatternTrendLine {
  x1: number;
  y1: number;
  x2: number;
  y2: number;
  kind: 'support' | 'resistance' | 'neckline' | 'breakout';
}

export interface TradingPatternSpec {
  id: number;
  name: string;
  family: PatternFamily;
  bias: PatternBias;
  reliability: 'High' | 'Medium' | 'Context';
  contextRule: string;
  anatomy: string;
  trigger: string;
  stopLoss: string;
  target: string;
  failureMode: string;
  candles: CandleRenderBar[];
  trendLines?: PatternTrendLine[];
}

export interface PatternQuizItem {
  id: string;
  question: string;
  options: string[];
  correctIndex: number;
  explanation: string;
}

